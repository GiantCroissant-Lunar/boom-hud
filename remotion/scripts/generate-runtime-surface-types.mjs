import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const QUICKTYPE_VERSION = "23.0.170";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const remotionRoot = resolve(scriptDir, "..");
const repoRoot = resolve(remotionRoot, "..");

const jobs = [
  {
    schema: resolve(repoRoot, "schemas/json/runtime-surface.schema.json"),
    out: resolve(remotionRoot, "src/runtime-surface/types.generated.ts"),
    topLevel: "RuntimeSurfaceDocument",
  },
  {
    schema: resolve(repoRoot, "schemas/json/runtime-node-graph.schema.json"),
    out: resolve(remotionRoot, "src/runtime-surface/node-graph.generated.ts"),
    topLevel: "RuntimeNodeGraphSnapshot",
  },
];

const quicktype = process.platform === "win32" ? "quicktype.cmd" : "quicktype";

for (const job of jobs) {
  const result = spawnSync(
    quicktype,
    [
      "--src",
      job.schema,
      "--src-lang",
      "schema",
      "--lang",
      "typescript",
      "--top-level",
      job.topLevel,
      "--just-types",
      "--prefer-types",
      "--explicit-unions",
      "--acronym-style",
      "pascal",
      "--out",
      job.out,
    ],
    {
      cwd: remotionRoot,
      stdio: "inherit",
      shell: process.platform === "win32",
    },
  );

  if (result.status !== 0) {
    process.exit(result.status ?? 1);
  }

  const schemaPath = relative(repoRoot, job.schema).replaceAll("\\", "/");
  const body = readFileSync(job.out, "utf8").replace(/^\uFEFF/, "");
  const header = [
    "// <auto-generated>",
    `// Generated by npm run generate:runtime-surface-types via quicktype ${QUICKTYPE_VERSION}.`,
    `// Source: ${schemaPath}`,
    "// </auto-generated>",
    "",
  ].join("\n");
  writeFileSync(job.out, header + body, "utf8");
}
